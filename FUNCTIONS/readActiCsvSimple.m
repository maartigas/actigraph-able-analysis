function T = readActiCsvSimple(path)
%READACTICSVSIMPLE Llegeix CSV simples d'ActiLife com HR, HRV o breathing.

lines = readlines(path);
cleanLines = lower(strtrim(lines));
headerRow = find(startsWith(cleanLines, "timestamp;") | ...
                 startsWith(cleanLines, "timestamp,") | ...
                 startsWith(cleanLines, "start;") | ...
                 startsWith(cleanLines, "start,") | ...
                 startsWith(cleanLines, "date;") | ...
                 startsWith(cleanLines, "date,"), 1);

delimiter = detectDelimiter(lines(headerRow));

opts = detectImportOptions(path, ...
    "Delimiter", delimiter, ...
    "NumHeaderLines", headerRow - 1, ...
    "VariableNamingRule", "preserve");

T = readtable(path, opts);
T.Properties.VariableNames = strtrim(T.Properties.VariableNames);
end
